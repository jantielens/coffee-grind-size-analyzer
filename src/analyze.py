def main():
    parser = argparse.ArgumentParser(
        description="Coffee grind size analysis — classical CV pipeline",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python analyze.py photo.jpg --grind-setting 45
  python analyze.py photos/ --output results/
  python analyze.py photos/ --model both          # watershed + cellpose comparison
  python analyze.py photo.jpg --report             # estimate grind setting
        """,
    )
    parser.add_argument(
        "input",
        type=Path,
        nargs="+",
        help="Image file(s) or directory of images",
    )
    parser.add_argument(
        "-o", "--output",
        type=Path,
        default=Path("results"),
        help="Output directory (default: results/)",
    )
    parser.add_argument(
        "-m", "--model",
        choices=["watershed", "cellpose", "both"],
        default="watershed",
        help="Which model(s) to run (default: watershed)",
    )
    parser.add_argument(
        "-g", "--grind-setting",
        type=int,
        default=None,
        help="Override grind setting for all images (0-100)",
    )
    parser.add_argument(
        "--expected-diam",
        type=float,
        default=0.7,
        help="Expected particle diameter in mm for Cellpose (default: 0.7)",
    )
    parser.add_argument(
        "--report",
        action="store_true",
        help="Report mode: estimate grind setting from unlabelled photos",
    )
    args = parser.parse_args()

    if args.report:
        report_process(args.input, args.output, args.expected_diam)
        return

    if args.model == "both":
        models = ["cellpose", "watershed"]
    else:
        models = [args.model]

    batch_process(args.input, args.output, models, args.grind_setting, args.expected_diam)


def _resolve_input_paths(inputs: list[Path]) -> list[Path]:
    """Expand a mix of files and directories into a flat list of image files."""
    image_files: list[Path] = []
    for p in inputs:
        if p.is_file() and p.suffix.lower() in IMAGE_EXTENSIONS:
            image_files.append(p)
        elif p.is_dir():
            image_files.extend(
                f for f in sorted(p.iterdir())
                if f.suffix.lower() in IMAGE_EXTENSIONS
            )
        else:
            print(f"⚠  Skipping {p} (not a recognised image file or directory)")
    return sorted(set(image_files), key=lambda f: f.name)


if __name__ == "__main__":
    main()
