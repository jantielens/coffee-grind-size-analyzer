def parse_grind_setting(filepath: str | Path) -> int | None:
    """Extract grind setting (0-100) from filename.  First integer found is used."""
    stem = Path(filepath).stem
    for m in re.finditer(r"(\d+)", stem):
        val = int(m.group(1))
        if 0 <= val <= 100:
            return val
    return None


def preprocess_image(
    image_path: Path,
    grind_setting: int | None,
    output_dir: Path,
) -> dict | None:
    """Load, detect markers, warp, normalise, mask.

    Returns a dict with all preprocessed data, or None on failure.
    """
    print(f"\n{'='*60}")
    print(f"Preprocessing: {image_path.name}  (grind setting: {grind_setting})")
    print(f"{'='*60}")

    image_bgr = cv2.imread(str(image_path))
    if image_bgr is None:
        print(f"  ✗ Could not load image")
        return None

    try:
        marker_centers = detect_aruco_markers(image_bgr)
        print(f"  ✓ Detected all 4 markers")
    except ValueError as e:
        print(f"  ✗ {e}")
        return None

    warped_bgr, mm_per_px = warp_to_canonical(image_bgr, marker_centers)
    print(f"  ✓ Warped ({warped_bgr.shape[1]}×{warped_bgr.shape[0]} px, "
          f"{mm_per_px:.4f} mm/px)")

    normed_bgr = normalize_white_balance(warped_bgr)
    normed_rgb = cv2.cvtColor(normed_bgr, cv2.COLOR_BGR2RGB)
    print(f"  ✓ White-balance normalised")

    masked_bgr = mask_markers(normed_bgr)
    masked_rgb = cv2.cvtColor(masked_bgr, cv2.COLOR_BGR2RGB)
    analysis_mask = get_analysis_mask(normed_bgr.shape[:2])

    img_out_dir = output_dir / image_path.stem
    img_out_dir.mkdir(parents=True, exist_ok=True)
    cv2.imwrite(str(img_out_dir / "warped.jpg"), warped_bgr, [cv2.IMWRITE_JPEG_QUALITY, 95])
    cv2.imwrite(str(img_out_dir / "normalized.jpg"), normed_bgr, [cv2.IMWRITE_JPEG_QUALITY, 95])

    return {
        "image_path": image_path,
        "grind_setting": grind_setting,
        "mm_per_px": mm_per_px,
        "normed_rgb": normed_rgb,
        "masked_rgb": masked_rgb,
        "analysis_mask": analysis_mask,
        "img_out_dir": img_out_dir,
    }


def segment_and_measure(
    prep: dict,
    model_name: str,
    expected_diam_mm: float = 0.7,
) -> dict | None:
    """Run one segmentation model + measure particles.

    Returns a dict with labels, dataframe, overlay, summary — or None on failure.
    """
    masked_rgb = prep["masked_rgb"]
    mm_per_px = prep["mm_per_px"]
    analysis_mask = prep["analysis_mask"]
    grind_setting = prep["grind_setting"]
    image_path = prep["image_path"]

    intermediates = {}
    try:
        if model_name == "cellpose":
            labels = segment_cellpose(masked_rgb, mm_per_px, expected_diam_mm)
        elif model_name == "watershed":
            labels, intermediates = segment_watershed(
                masked_rgb, mm_per_px, return_intermediates=True,
            )
        else:
            print(f"  ✗ Unknown model: {model_name}")
            return None
    except Exception as e:
        print(f"  ✗ {model_name} failed: {e}")
        return None

    n_raw = labels.max()
    image_gray = cv2.cvtColor(masked_rgb, cv2.COLOR_RGB2GRAY)
    df = measure_particles(labels, mm_per_px, analysis_mask, image_gray=image_gray)

    print(f"  ✓ {model_name}: {n_raw} raw → {len(df)} particles", end="")
    if not df.empty:
        med = df["equiv_diameter_mm"].median()
        mean = df["equiv_diameter_mm"].mean()
        print(f"  (median={med:.3f}  mean={mean:.3f} mm)")
    else:
        print()

    # Build overlay using only the labels that survived filtering
    if not df.empty:
        kept = set(df["label"].values)
        filtered = labels.copy()
        filtered[~np.isin(labels, list(kept))] = 0
        filtered = _relabel_sequential(filtered)
    else:
        filtered = np.zeros_like(labels)
    overlay = create_overlay(prep["normed_rgb"], filtered)

    dist_stats = compute_distribution_stats(df)

    summary = {
        "image": image_path.name,
        "grind_setting": grind_setting,
        "model": model_name,
        "n_particles": len(df),
        "median_diameter_mm": round(df["equiv_diameter_mm"].median(), 4) if not df.empty else None,
        "mean_diameter_mm": round(df["equiv_diameter_mm"].mean(), 4) if not df.empty else None,
        "std_diameter_mm": round(df["equiv_diameter_mm"].std(), 4) if not df.empty else None,
        "q25_diameter_mm": round(df["equiv_diameter_mm"].quantile(0.25), 4) if not df.empty else None,
        "q75_diameter_mm": round(df["equiv_diameter_mm"].quantile(0.75), 4) if not df.empty else None,
        "total_area_mm2": round(df["area_mm2"].sum(), 4) if not df.empty else None,
        **dist_stats,
    }

    return {
        "model_name": model_name,
        "labels": labels,
        "df": df,
        "overlay": overlay,
        "summary": summary,
        "intermediates": intermediates,
    }


def save_model_results(prep: dict, result: dict) -> None:
    """Write overlay, distribution plot, CSV, and summary PNG to disk."""
    img_out_dir = prep["img_out_dir"]
    grind_setting = prep["grind_setting"]
    model_name = result["model_name"]
    df = result["df"]
    overlay = result["overlay"]
    image_path = prep["image_path"]

    overlay_bgr = cv2.cvtColor(overlay, cv2.COLOR_RGB2BGR)
    cv2.imwrite(
        str(img_out_dir / f"overlay_{model_name}.jpg"),
        overlay_bgr, [cv2.IMWRITE_JPEG_QUALITY, 95],
    )

    fig = plot_distribution(df, model_name, grind_setting)
    if fig is not None:
        fig.tight_layout()
        fig.savefig(img_out_dir / f"distribution_{model_name}.png", dpi=150)
        plt.close(fig)

    if not df.empty:
        df_out = df.copy()
        df_out["grind_setting"] = grind_setting
        df_out["model"] = model_name
        df_out["image"] = image_path.name
        df_out.to_csv(img_out_dir / f"particles_{model_name}.csv", index=False)

    # Pipeline summary PNG (watershed only — has intermediates)
    if model_name == "watershed":
        save_pipeline_summary(prep, result)


