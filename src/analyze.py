def report_process(
    input_paths: Path | list[Path],
    output_dir: Path,
    expected_diam_mm: float = 0.7,
) -> None:
    """Process unlabelled photos and estimate grind settings.

    For each image: preprocess -> segment (watershed) -> measure ->
    estimate DF54 grind setting from median diameter -> save summary.png.
    """
    output_dir.mkdir(parents=True, exist_ok=True)

    if isinstance(input_paths, Path):
        input_paths = [input_paths]

    image_files = _resolve_input_paths(input_paths)
    if not image_files:
        print(f"No images found in {input_paths}")
        sys.exit(1)

    print(f"Report mode: {len(image_files)} image(s)")
    print(f"Output: {output_dir.resolve()}")

    t0 = time.perf_counter()
    reports: list[dict] = []

    for img_path in image_files:
        prep = preprocess_image(img_path, None, output_dir)
        if prep is None:
            continue

        result = segment_and_measure(prep, "watershed", expected_diam_mm)
        if result is None:
            continue

        # Estimate grind setting from median particle diameter
        median_d = result["summary"]["median_diameter_mm"]
        if median_d is not None:
            est = estimate_grind_setting(median_d)
            est_rounded = round(est)
        else:
            est = None
            est_rounded = None

        # Store estimated setting in prep so visualization shows it
        prep["grind_setting"] = est_rounded
        prep["grind_setting_estimated"] = True
        result["summary"]["grind_setting"] = est_rounded
        result["summary"]["estimated_grind_setting"] = round(est, 1) if est is not None else None

        save_model_results(prep, result)

        reports.append({
            "image": img_path.name,
            "median_diameter_mm": median_d,
            "estimated_df54_setting": round(est, 1) if est is not None else None,
            "n_particles": result["summary"]["n_particles"],
            "mean_diameter_mm": result["summary"]["mean_diameter_mm"],
            "std_diameter_mm": result["summary"]["std_diameter_mm"],
            "D10": result["summary"]["D10"],
            "D50": result["summary"]["D50"],
            "D90": result["summary"]["D90"],
            "span": result["summary"]["span"],
            "fines_pct": result["summary"]["fines_pct"],
            "boulders_pct": result["summary"]["boulders_pct"],
            "D_4_3": result["summary"]["D_4_3"],
            "D_3_2": result["summary"]["D_3_2"],
        })

        print(f"  >> Estimated DF54 setting: ~{est_rounded}"
              f"  (median {median_d:.3f} mm)" if median_d else "")

    if not reports:
        print("\nNo images were processed successfully.")
        return

    # Summary table
    report_df = pd.DataFrame(reports)
    report_path = output_dir / "report.csv"
    report_df.to_csv(report_path, index=False)

    print(f"\n{'='*60}")
    print("REPORT")
    print(f"{'='*60}")
    print(report_df.to_string(index=False))
    print(f"\nReport saved to: {report_path}")

    elapsed = time.perf_counter() - t0
    print(f"Total time: {elapsed:.1f}s")


