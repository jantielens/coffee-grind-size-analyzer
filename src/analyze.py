#!/usr/bin/env python3
"""
Coffee grind size analysis — classical computer vision pipeline.

Segments coffee particles from photos taken on an ArUco reference sheet
(generated by generate-reference-sheet.py) and measures their size
distribution.

Pipeline:
    1. Detect ArUco markers (IDs 0-3) in photo
    2. Compute homography → warp to canonical view (known mm/px scale)
    3. White-balance normalise using marker black + paper white references
    4. Segment particles (adaptive threshold + watershed)
    5. Measure each particle (area, equivalent diameter, axes, shape)
    6. Generate visual overlays, distribution plots, pipeline summary
    7. Aggregate across grind settings → correlation plots

Usage:
    # Single image
    python analyze.py photo.jpg --grind-setting 45 --output results/

    # Batch — filename must contain grind setting as a number
    python analyze.py photos/ --output results/

    # Cellpose comparison (requires cellpose + GPU)
    python analyze.py photos/ --model both
"""

