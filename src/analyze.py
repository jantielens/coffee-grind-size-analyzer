# Batch processing
# ---------------------------------------------------------------------------

def batch_process(
    input_paths: Path | list[Path],
    output_dir: Path,
    models: list[str],
    grind_setting_override: int | None = None,
    expected_diam_mm: float = 0.7,
) -> None:
    """Process one or more images / directories sequentially.

    For each image: preprocess → segment with each model → save results.
    After all images: write summary CSV and correlation plot.
    """
    output_dir.mkdir(parents=True, exist_ok=True)

    if isinstance(input_paths, Path):
        input_paths = [input_paths]

    image_files = _resolve_input_paths(input_paths)
    if not image_files:
        print(f"No images found in {input_paths}")
        sys.exit(1)

    # Build (path, grind_setting) pairs
    jobs: list[tuple[Path, int]] = []
    for img_path in image_files:
        gs = grind_setting_override if grind_setting_override is not None else parse_grind_setting(img_path)
        if gs is None:
            print(f"⚠  Cannot determine grind setting for {img_path.name} — skipping.")
            continue
        jobs.append((img_path, gs))

    print(f"Found {len(jobs)} image(s)")
    print(f"Models: {', '.join(models)}")
    print(f"Output: {output_dir.resolve()}")

    t0 = time.perf_counter()
    all_summaries: list[dict] = []

    for path, gs in jobs:
        prep = preprocess_image(path, gs, output_dir)
        if prep is None:
            continue

        for model_name in models:
            result = segment_and_measure(prep, model_name, expected_diam_mm)
            if result is not None:
                save_model_results(prep, result)
                all_summaries.append(result["summary"])

        # Comparison image when running multiple models
        if len(models) >= 2:
            save_comparison(prep["img_out_dir"], prep["normed_rgb"], models, gs)

    if not all_summaries:
        print("\nNo images were processed successfully.")
        return

    # Aggregate summary
    summary_df = pd.DataFrame(all_summaries)
    summary_path = output_dir / "summary.csv"
    summary_df.to_csv(summary_path, index=False)
    print(f"\n{'='*60}")
    print(f"Summary saved to: {summary_path}")
    print("\n" + summary_df.to_string(index=False))

    if len(summary_df["grind_setting"].dropna().unique()) > 1:
        plot_correlation(summary_df, output_dir)

    elapsed = time.perf_counter() - t0
    print(f"\nTotal time: {elapsed:.1f}s")


# ---------------------------------------------------------------------------
# CLI
